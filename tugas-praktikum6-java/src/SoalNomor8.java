public class SoalNomor8 {
    public static void main(String[] args) {
        
        int[] angkaArray = {10, 20, 30, 40, 50};

        System.out.println("Menampilkan nilai array menggunakan foreach:");
       
        for (int angka : angkaArray) {
            System.out.println(angka);
        }
    }
}